// Simple PDFs made on request from the records this system holds: a purchase
// order and a delivery slip (goods receipts). They are views of the stored
// data, not the supplier's or the warehouse's original documents, and say so
// on the page. Standard PDF fonts only (Helvetica): nothing is embedded or
// fetched. pdfkit is the only library used.

import PDFDocument from 'pdfkit';
import { fmtMoney } from '../agent/finance/validation.js';

const PAGE = { size: 'A4', margin: 50 };
const COLS = [
  { key: 'sku', label: 'Item code', x: 50, w: 80 },
  { key: 'description', label: 'Description', x: 135, w: 190 },
  { key: 'qty', label: 'Quantity', x: 330, w: 55, align: 'right' },
  { key: 'unitPrice', label: 'Unit price', x: 390, w: 70, align: 'right' },
  { key: 'total', label: 'Line total', x: 465, w: 80, align: 'right' },
];

const round2 = (n) => Math.round(n * 100) / 100;

/** Run `build(doc)` and collect the PDF as a Buffer. */
function render(info, build) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ ...PAGE, info });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    try {
      build(doc);
      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

function heading(doc, title, lines, note) {
  doc.font('Helvetica-Bold').fontSize(18).text(title, 50, 50);
  doc.moveDown(0.4).font('Helvetica').fontSize(9).fillColor('#5b6672').text(note, { width: 495 });
  doc.fillColor('#000').moveDown(0.8).fontSize(10);
  for (const [label, value] of lines) {
    doc
      .font('Helvetica-Bold')
      .text(`${label}: `, { continued: true })
      .font('Helvetica')
      .text(value ?? '-');
  }
  doc.moveDown(1);
}

function table(doc, rows, currency) {
  const header = (y) => {
    doc.font('Helvetica-Bold').fontSize(9);
    for (const c of COLS) doc.text(c.label, c.x, y, { width: c.w, align: c.align || 'left' });
    doc
      .moveTo(50, y + 13)
      .lineTo(545, y + 13)
      .strokeColor('#999')
      .stroke();
    return y + 18;
  };
  let y = header(doc.y);
  doc.font('Helvetica').fontSize(9);
  for (const r of rows) {
    const cells = {
      sku: r.sku || '-',
      description: r.description || '-',
      qty: String(r.qty ?? '-'),
      unitPrice: fmtMoney(r.unitPrice, currency),
      total: fmtMoney(r.total, currency),
    };
    const height = Math.max(...COLS.map((c) => doc.heightOfString(cells[c.key], { width: c.w })));
    if (y + height > 760) {
      doc.addPage();
      y = header(50);
      doc.font('Helvetica').fontSize(9);
    }
    for (const c of COLS) doc.text(cells[c.key], c.x, y, { width: c.w, align: c.align || 'left' });
    y += height + 6;
  }
  doc.y = y + 4;
}

function totals(doc, lines, currency) {
  doc.fontSize(10);
  for (const [label, value, bold] of lines) {
    const y = doc.y;
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').text(label, 330, y, { width: 130, align: 'right' });
    doc.text(fmtMoney(value, currency), 465, y, { width: 80, align: 'right' });
    doc.moveDown(0.3);
  }
}

const NOTE = 'Generated by the Finance Operations Agent from the record held in this system (sample data). It is not the original document.';

/**
 * A purchase order as a PDF.
 * @param po { poNumber, vendorName, vendorAbn, raisedOn, lines: [{ sku, description, qty, unitPrice }] }
 */
export function purchaseOrderPdf(po, { companyName, gstRatePct = 10, currency = 'AUD' } = {}) {
  const rows = (po.lines || []).map((l) => ({ ...l, total: round2((l.qty || 0) * (l.unitPrice || 0)) }));
  const subtotal = round2(rows.reduce((s, r) => s + r.total, 0));
  const gst = round2((subtotal * gstRatePct) / 100);
  return render(
    { Title: `Purchase order ${po.poNumber}`, Author: companyName || 'Finance Operations Agent', Subject: `Purchase order ${po.poNumber} to ${po.vendorName || ''}` },
    (doc) => {
      heading(
        doc,
        `Purchase order ${po.poNumber}`,
        [
          ['Purchase order number', po.poNumber],
          ['Raised on', po.raisedOn],
          ['Buyer', companyName],
          ['Supplier', po.vendorName],
          ['Supplier ABN', po.vendorAbn],
        ],
        NOTE,
      );
      table(doc, rows, currency);
      totals(
        doc,
        [
          ['Subtotal', subtotal],
          [`GST (${gstRatePct}%)`, gst],
          ['Total', round2(subtotal + gst), true],
        ],
        currency,
      );
    },
  );
}

/**
 * A delivery slip as a PDF: every goods receipt recorded against the purchase
 * order, with the PO's descriptions and prices for the quantities received.
 * @param receipts [{ poNumber, receivedOn, lines: [{ sku, qty }] }]
 */
export function deliverySlipPdf(po, receipts, { companyName, currency = 'AUD' } = {}) {
  const priceOf = new Map((po.lines || []).map((l) => [String(l.sku || '').toUpperCase(), l]));
  return render({ Title: `Delivery slip for ${po.poNumber}`, Author: companyName || 'Finance Operations Agent', Subject: `Goods received against ${po.poNumber}` }, (doc) => {
    heading(
      doc,
      'Delivery slip (goods received)',
      [
        ['Purchase order number', po.poNumber],
        ['Supplier', po.vendorName],
        ['Supplier ABN', po.vendorAbn],
        ['Received by', companyName],
        ['Deliveries recorded', String(receipts.length)],
      ],
      NOTE,
    );
    let all = 0;
    receipts.forEach((r, i) => {
      doc
        .font('Helvetica-Bold')
        .fontSize(11)
        .text(`Delivery ${i + 1}: received on ${r.receivedOn || 'unknown date'}`, 50);
      doc.moveDown(0.4);
      const rows = (r.lines || []).map((l) => {
        const p = priceOf.get(String(l.sku || '').toUpperCase());
        return { sku: l.sku, description: p?.description, qty: l.qty, unitPrice: p?.unitPrice ?? null, total: p ? round2(l.qty * p.unitPrice) : null };
      });
      table(doc, rows, currency);
      const value = round2(rows.reduce((s, x) => s + (x.total || 0), 0));
      all += value;
      totals(doc, [['Value received (excl. GST)', value, true]], currency);
      doc.moveDown(0.8);
    });
    if (receipts.length > 1) totals(doc, [['All deliveries (excl. GST)', round2(all), true]], currency);
  });
}
